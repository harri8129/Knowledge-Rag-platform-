import re 

CITATION_PATTERN = re.compile(
    r"\[S(\d+)\]"
)

def extract_citation_ids(answer: str,) -> list[str]:
    """
    Extract citations such as:

        [S1]
        [S2]
        [S1][S3]
    """

    matches = CITATION_PATTERN.findall(answer)

    citation_ids = []

    for number in matches:
        source_id = f"S{number}"

        if source_id not in citation_ids:
           citation_ids.append(source_id)

    return citation_ids


def validation_citations(answer:str, sources: list[dict],) -> dict:
    """
    Validat citations generated by the llm 
    """

    cited_ids = extract_citation_ids(answer)

    valid_ids = {
        source["source_id"]
        for source in sources
    }

    valid_citations = [
        citation
        for citation in cited_ids
        if citation in valid_ids
    ]

    invalid_citations = [
        citation
        for citation in cited_ids
        if citation not in valid_ids
    ]

    return {
        "cited_sources": valid_citations,
        "invalid_citations": invalid_citations,
        "citation_count": len(
            valid_citations
        ),
        "has_invalid_citations": bool(
            invalid_citations
        ),
    }